-- =====================================================================
-- Migration 002 — διαγραφή μηνυμάτων ανά χρήστη (soft delete)
-- =====================================================================
-- ΓΙΑΤΙ:
--   Η εκφώνηση §10 το απαιτεί ρητά: «Οι χρήστες θα μπορούν να διαγράφουν
--   μηνύματα από τους καταλόγους εισερχομένων / απεσταλμένων.»
--
--   Η ίδια γραμμή του `messages` όμως εξυπηρετεί ΚΑΙ τις δύο πλευρές: είναι
--   το εισερχόμενο του παραλήπτη και το απεσταλμένο του αποστολέα. Σκέτο
--   DELETE θα έσβηνε το μήνυμα και από τον άλλον χρήστη — δηλαδή ο ένας θα
--   μπορούσε να εξαφανίσει αποδεικτικά στοιχεία από τον κατάλογο του άλλου.
--
--   Λύση: δύο ανεξάρτητες σημαίες. Ο καθένας κρύβει το μήνυμα μόνο από τον
--   δικό του κατάλογο. Όταν το κρύψουν ΚΑΙ ΟΙ ΔΥΟ, η γραμμή δεν είναι πλέον
--   ορατή σε κανέναν και το API τη διαγράφει οριστικά (βλ. routers/messages.py).
--
-- ΑΣΦΑΛΕΙΑ: προσθήκη στηλών με DEFAULT 0 — τα υπάρχοντα μηνύματα μένουν
--   ορατά και στις δύο πλευρές, καμία απώλεια δεδομένων.
--
-- ΕΚΤΕΛΕΣΗ:  mysql -u root -p staywebapp < db/migrations/002_messages_soft_delete.sql
-- =====================================================================

USE `staywebapp`;

ALTER TABLE `messages`
  ADD COLUMN `deleted_by_sender`   TINYINT(1) NOT NULL DEFAULT 0
    COMMENT 'Ο αποστολέας το έκρυψε από τα απεσταλμένα του',
  ADD COLUMN `deleted_by_receiver` TINYINT(1) NOT NULL DEFAULT 0
    COMMENT 'Ο παραλήπτης το έκρυψε από τα εισερχόμενά του';

-- Τα εισερχόμενα και το unread-count φιλτράρουν πάντα με (to_user_id,
-- deleted_by_receiver)· το unread-count το κάνει poll κάθε 30s ο browser.
CREATE INDEX `idx_messages_inbox`
  ON `messages` (`to_user_id`, `deleted_by_receiver`);

CREATE INDEX `idx_messages_outbox`
  ON `messages` (`from_user_id`, `deleted_by_sender`);
